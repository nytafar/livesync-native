const nameLists = [[".gitignore"], [".gitignore", ".obsidianignore"], [".obsidianignore", ".gitignore"], []];

async function generateAll(emit) {
    const cases = [];
    for (const names of nameLists) {
        for (const path of vaultPaths) {
            const asked = [];
            const getList = async (p) => {
                asked.push(p);
                // As upstream's own unit test and Obsidian's adapter do: a
                // leading "/" names the vault root.
                const key = p.startsWith("/") ? p.substring(1) : p;
                if (!(key in vault)) return false;
                return vault[key].split(/\r?\n/g).map((e) => e.replace(/\r$/, "").trim());
            };
            const ok = await isAcceptedAll(path, names, getList);
            cases.push({ ignoreFiles: names, path, accepted: ok, asked });
        }
    }
    emit("ignore_all.json", cases, { vault });
}
