export function generateIgnore(emit) {
    // One case per ignore file: its lines, and one character per path in
    // `paths` (t accepted, f ignored, - not mentioned).
    const cases = [];
    const lists = [...single.map((p) => [p]), ...multi];
    for (const lines of lists) {
        let results = "";
        for (const path of paths) {
            const r = isAccepted(path, lines);
            results += r === undefined ? "-" : r ? "t" : "f";
        }
        cases.push({ lines, results });
    }
    emit("ignore_accepted.json", cases, { paths });
    return generateAll(emit);
}

